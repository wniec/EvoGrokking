def _config_with(**kw):
    import neat

    from evogrokking.neat_arch import ArchGenome

    path = write_config(os.path.join(tempfile.mkdtemp(), "neat.ini"), **kw)
    return neat.Config(
        ArchGenome, neat.DefaultReproduction, neat.DefaultSpeciesSet,
        neat.DefaultStagnation, path,
    )


def test_mutation_rounds_scale_the_structural_step():
    # neat-python changes at most one gene of each kind per genome per
    # generation, which is a negligible step for a dense genome.  Repeating the
    # operators must move proportionally more genes.  Exercised directly on
    # `mutate` so the measurement is of the operator, not of selection.
    import random as _random

    def churn(rounds):
        cfg = _config_with(
            pop_size=4, n_inputs=60, n_outputs=5, n_hidden=12,
            structural_mutation_rounds=rounds,
        )
        _random.seed(0)
        pop = __import__("neat").Population(cfg, seed=0)
        genome = next(iter(pop.population.values()))
        before = len(genome.connections)
        genome.mutate(cfg.genome_config)
        return abs(before - len(genome.connections))

    one, many = churn(1), churn(60)
    # A single round touches at most a handful of genes (each add-node adds two
    # connection genes plus disables one); 60 rounds must move far more.
    assert one <= 6, f"a single round moved {one} connections -- expected a handful"
    assert many > 8 * max(one, 1), f"60 rounds moved only {many} vs {one} for one"


def test_mutation_rounds_reach_the_genome_config():
    import neat

    from evogrokking.neat_arch import ArchGenome

    path = write_config(
        os.path.join(tempfile.mkdtemp(), "neat.ini"),
        pop_size=4, n_inputs=6, n_outputs=2, n_hidden=3,
        structural_mutation_rounds=17,
    )
    cfg = neat.Config(
        ArchGenome, neat.DefaultReproduction, neat.DefaultSpeciesSet,
        neat.DefaultStagnation, path,
    )
    assert cfg.genome_config.structural_mutation_rounds == 17
    # It is ours, not neat-python's: it must not leak into the library's params.
    assert "structural_mutation_rounds" not in [p.name for p in cfg.genome_config._params]


def test_partial_initial_connectivity_diversifies_the_founders():
    # Fully wired founders are byte-identical, so generation 0 trains the same
    # network pop_size times.  A fraction below 1 gives each its own subset.
    import neat

    from evogrokking.neat_arch import ArchGenome

    def founders(fraction):
        path = write_config(
            os.path.join(tempfile.mkdtemp(), "neat.ini"),
            pop_size=8, n_inputs=40, n_outputs=5, n_hidden=10,
            initial_connection_fraction=fraction,
        )
        cfg = neat.Config(
            ArchGenome, neat.DefaultReproduction, neat.DefaultSpeciesSet,
            neat.DefaultStagnation, path,
        )
        pop = neat.Population(cfg, seed=0)
        genomes = list(pop.population.values())
        distances = {genomes[0].distance(g, cfg.genome_config) for g in genomes[1:]}
        return genomes, distances, len(pop.species.species)

    _full, full_d, full_species = founders(1.0)
    part, part_d, part_species = founders(0.5)

    assert full_d == {0.0} and full_species == 1  # all clones, one species
    assert min(part_d) > 0.0 and part_species > 1  # genuinely diverse
    # ...and sparser: roughly half the wiring.
    full_conns = len(_full[0].connections)
    assert 0.4 * full_conns < len(part[0].connections) < 0.6 * full_conns


def test_initial_connection_fraction_is_validated():
    kw = dict(pop_size=4, n_inputs=6, n_outputs=2, n_hidden=3)
    for bad in (0.0, -0.5, 1.5):
        try:
            write_config(os.path.join(tempfile.mkdtemp(), "n.ini"),
                         initial_connection_fraction=bad, **kw)
        except ValueError:
            continue
        raise AssertionError(f"expected ValueError for fraction={bad}")


def test_neat_population_evolves_and_converts_to_genomes():
    pop, _ = neat_population(pop_size=10)
    pop.run(random_fitness(random.Random(0)), 5)
    assert pop.best_genome is not None

    g = to_genome(pop.best_genome, 6, 3)
    ids = g.node_ids()
    for c in g.conns:
        assert c.src in ids and c.dst in ids
    for node in ids:
        assert node not in reachable_all(g.conns, node)  # still a DAG
    for n in g.nodes:
        assert n.activation in ("relu", "gelu", "tanh", "silu")


def test_evolution_can_grow_past_one_hidden_layer():
    # The dense start is a single hidden layer; add-node mutations must be able
    # to deepen it, otherwise the search could only ever prune width.
    from evogrokking.models import _levels

    pop, _ = neat_population(pop_size=16, n_inputs=20, n_outputs=3, n_hidden=8, seed=1)

    def hidden_depth(neat_genome):
        g = to_genome(neat_genome, 20, 3)
        return len(_levels(g.conns, g.node_ids(), set(g.input_ids()))) - 2

    assert {hidden_depth(g) for g in pop.population.values()} == {1}  # dense start
    pop.run(random_fitness(random.Random(0)), 10)
    assert max(hidden_depth(g) for g in pop.population.values()) > 1


def test_neat_genome_builds_a_trainable_model():
    pop, _ = neat_population(pop_size=6, n_inputs=20, n_outputs=3, seed=5)
    pop.run(random_fitness(random.Random(2)), 3)

    spec = datasets.DatasetSpec("t", "image", input_dim=20, num_classes=3)
    for ng in pop.population.values():
        model = build_model(to_genome(ng, 20, 3), spec)
        assert model(torch.randn(4, 20)).shape == (4, 3)
