def test_founding_population_shares_its_hidden_neurons():
    # neat-python normally hands each founding genome its OWN hidden keys, which
    # makes the whole population mutually non-homologous -- every genome its own
    # species, crossover reduced to copying.  ArchGenome fixes that.
    pop, cfg = neat_population(pop_size=10, n_inputs=20, n_hidden=8)
    genomes = list(pop.population.values())
    keys = [sorted(k for k in g.nodes if k >= 3) for g in genomes]
    assert all(k == keys[0] for k in keys), "founding genomes must share hidden keys"
    assert genomes[0].distance(genomes[1], cfg.genome_config) == 0.0
    assert len(pop.species.species) == 1  # ...so they start as one species


def test_weights_and_biases_are_not_evolved():
    # They come from gradient descent, so their genes stay pinned and contribute
    # nothing to the genomic distance.
    pop, _ = neat_population(pop_size=6, n_inputs=8, n_hidden=4)
    genomes = list(pop.population.values())
    weights = {c.weight for g in genomes for c in g.connections.values()}
    biases = {n.bias for g in genomes for n in g.nodes.values()}
    assert weights == {1.0}
    assert biases == {0.0}


